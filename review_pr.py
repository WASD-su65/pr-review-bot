import sys

from reviewer import summarize_diff

MAX_DIFF_CHARS = 100_000
DISCLAIMER = "_Generated by a language model. It may be inaccurate; treat it as a hint for a human reviewer._"


def format_comment(result: dict, truncated: bool = False) -> str:
    lines = ["### Automated review", "", f"**Summary:** {result['summary']}", "", "**Notes:**"]
    lines += [f"- {note}" for note in result["notes"]]
    if truncated:
        lines += ["", "_The diff was too large and was cut before review._"]
    lines += ["", DISCLAIMER]
    return "\n".join(lines)


def main(diff_path: str, out_path: str) -> None:
    diff = open(diff_path, encoding="utf-8").read()
    if not diff.strip():
        body = "### Automated review\n\nNo changes to review."
    else:
        truncated = len(diff) > MAX_DIFF_CHARS
        try:
            result = summarize_diff(diff[:MAX_DIFF_CHARS])
            body = format_comment(result, truncated)
        except Exception as e:
            body = f"### Automated review\n\nThe review could not be generated ({type(e).__name__})."
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(body)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])